import { test, expect } from '@playwright/test'

test.describe('Uçtan uca duman testi', () => {
  test('örnek dosya yüklenir, sayaç ve kartlar Excel ile uyumlu', async ({ page }) => {
    await page.goto('/dosya/giris')
    await expect(page.getByRole('heading', { name: 'Kapak ve Dosya Kimliği' })).toBeVisible()
    await page.getByRole('button', { name: /Örnek dosyayı yükle/ }).click()
    await expect(page.getByText('ETKEN 3')).toBeVisible()
    await expect(page.getByText('İNCELENMELİ 7')).toBeVisible()
    await page.getByRole('link', { name: /3\. Yol ve Çevre/ }).click()
    await expect(page.getByRole('heading', { name: '2. Yol ve Çevre' })).toBeVisible()
    await expect(page.getByText('Şafak VaktiYönetmeliğe uygun güvenlik önleminin alınması').first()).toBeVisible()
    await page.getByRole('button', { name: 'Neden?' }).first().click()
    await expect(page.getByText('İspat zinciri')).toBeVisible()
    await page.keyboard.press('Escape')
  })
  test('bir girdi değişince kart ve sayaç güncellenir', async ({ page }) => {
    await page.goto('/dosya/giris')
    await page.getByRole('button', { name: /Örnek dosyayı yükle/ }).click()
    await expect(page.getByText('ETKEN 3')).toBeVisible()
    await page.getByRole('link', { name: /3\. Yol ve Çevre/ }).click()
    const card = page.locator('[id="kart-yol-cevre.gun-durumu-0"]')
    await card.getByRole('button', { name: 'Aranmadı', exact: true }).click()
    await expect(card.getByText('ETKEN DEĞİL').first()).toBeVisible()
    await expect(page.getByText('ETKEN 2')).toBeVisible()
    await expect(card.getByText('Yönetmeliğe uygun güvenlik önlemi alınmıştır.')).toBeVisible()
  })
  test('dosya türü değişince taraf etiketleri değişir', async ({ page }) => {
    await page.goto('/dosya/giris')
    await page.getByRole('button', { name: /Örnek dosyayı yükle/ }).click()
    await expect(page.getByText('ETKEN 3')).toBeVisible()
    await page.getByLabel(/Dosya türü/).selectOption('hukuk')
    await page.locator('nav').getByRole('link', { name: /Veri Girişi/ }).click()
    await expect(page.getByText('DAVACI', { exact: true })).toBeVisible()
  })
  test('sonuç ve rapor önizleme açılır', async ({ page }) => {
    await page.goto('/dosya/giris')
    await page.getByRole('button', { name: /Örnek dosyayı yükle/ }).click()
    await expect(page.getByText('ETKEN 3')).toBeVisible()
    await page.getByRole('link', { name: /Sonuç Özeti/ }).click()
    await expect(page.getByText('Toplam (sonuç1!A1)')).toBeVisible()
    await page.getByRole('link', { name: /Rapor Önizleme/ }).click()
    await expect(page.getByRole('heading', { name: /Rapor Önizleme/ })).toBeVisible()
    await page.goto('/modul/gunes/hesap')
    await expect(page.getByText('Elevasyon (°)')).toBeVisible({ timeout: 15000 })
  })
})
